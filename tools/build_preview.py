"""Build a self-contained, disposable preview; no server or dependencies needed.

Run: python3 tools/build_preview.py [--output /path/to/preview.html | --share]
The normal multi-file application is never modified by this script.
"""
import argparse
import base64
import hashlib
import html
import json
from pathlib import Path
import re
from zipfile import BadZipFile, ZIP_DEFLATED, ZipFile

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by tools/build_preview.py; edit source files, then rebuild. -->'


def inline_text(source, tag):
    """Prevent a string/comment from prematurely closing an HTML raw-text tag."""
    return re.sub(r'</' + tag, lambda match: '<\\/' + tag, source, flags=re.I)


def local_asset(name):
    path = (ROOT / name.split('?', 1)[0].removeprefix('./')).resolve()
    if not path.is_relative_to(ROOT) or not path.is_file():
        raise ValueError(f'Preview requires a local asset: {name}')
    return path


def build_preview():
    source = (ROOT / 'index.html').read_text(encoding='utf-8')
    fixtures = {
        'demo/accounts.json': json.loads((ROOT / 'demo/accounts.json').read_text(encoding='utf-8')),
        'packs/community.json': json.loads((ROOT / 'packs/community.json').read_text(encoding='utf-8')),
    }
    encoded = json.dumps(fixtures, ensure_ascii=True).replace('<', '\\u003c')
    bootstrap = r"""
// This generated preview always uses disposable storage, never saved app data.
window.KS_PREVIEW = true;
(() => {
  function memoryStorage() {
    const values = new Map();
    return Object.freeze({
      get length() { return values.size; },
      getItem(key) { return values.get(String(key)) ?? null; },
      setItem(key, value) { values.set(String(key), String(value)); },
      removeItem(key) { values.delete(String(key)); },
      clear() { values.clear(); },
      key(index) { return [...values.keys()][index] ?? null; }
    });
  }
  for (const name of ['localStorage', 'sessionStorage']) {
    Object.defineProperty(window, name, {configurable: true, value: memoryStorage()});
  }
  // Embedded viewers may deny native form submission, even when no navigation
  // is intended. Dispatch to the app's existing submit handlers inside this
  // disposable preview only; production forms keep their normal behavior.
  function submitPreviewForm(form, submitter) {
    if (form.noValidate || form.reportValidity()) {
      form.dispatchEvent(new SubmitEvent('submit', {
        bubbles: true, cancelable: true, submitter
      }));
    }
  }
  document.addEventListener('click', event => {
    const submitter = event.target.closest('button, input[type="submit"]');
    if (!submitter?.form || submitter.type !== 'submit' || submitter.disabled) return;
    event.preventDefault();
    submitPreviewForm(submitter.form, submitter);
  }, true);
  document.addEventListener('keydown', event => {
    const target = event.target;
    if (event.key !== 'Enter' || event.isComposing || target.tagName !== 'INPUT' || !target.form) return;
    const submitter = [...target.form.elements].find(control => control.type === 'submit' && !control.disabled);
    if (!submitter) return;
    event.preventDefault();
    submitPreviewForm(target.form, submitter);
  });
  const fixtures = __FIXTURES__;
  window.fetch = async (input, options = {}) => {
    if (options.signal?.aborted) throw new DOMException('Request aborted', 'AbortError');
    const raw = typeof input === 'string' ? input : input?.url || '';
    const path = raw.split('?', 1)[0].replace(/^\.\//, '').replace(/^\//, '');
    if (!Object.hasOwn(fixtures, path)) {
      throw new TypeError('This preview has no network connection for that resource.');
    }
    return new Response(JSON.stringify(fixtures[path]), {
      status: 200, headers: {'Content-Type': 'application/json'}
    });
  };
})();
""".replace('__FIXTURES__', encoded)

    def embed_link(match):
        tag = match[0]
        rel = re.search(r'\brel="([^"]+)"', tag)
        href = re.search(r'\bhref="([^"]+)"', tag)
        if not rel or not href:
            raise ValueError(f'Unsupported preview link: {tag}')
        if rel[1] == 'stylesheet':
            css = local_asset(href[1]).read_text(encoding='utf-8')
            return '<style>' + inline_text(css, 'style') + '</style>'
        if rel[1] in ('icon', 'apple-touch-icon'):
            image = base64.b64encode(local_asset(href[1]).read_bytes()).decode('ascii')
            return f'<link rel="{rel[1]}" href="data:image/png;base64,{image}">'
        if rel[1] == 'manifest':
            return ''  # The disposable preview is not an installable PWA.
        raise ValueError(f'Unsupported preview link: {tag}')

    def embed_script(match):
        path = local_asset(match[1])
        code = inline_text(path.read_text(encoding='utf-8'), 'script')
        return f'<script data-source="{html.escape(match[1], quote=True)}">\n{code}\n</script>'

    source = re.sub(r'<link\b[^>]*>', embed_link, source)
    source = re.sub(
        r'<script\b[^>]*\bsrc="([^"]+)"[^>]*>\s*</script>', embed_script, source
    )
    source = source.replace('</head>', '<script>\n' + inline_text(bootstrap, 'script') + '</script>\n</head>', 1)
    note = '<aside data-preview-note class="preview-note">Demo preview · changes reset when reloaded.</aside>'
    source = source.replace('<div class="app-shell">', '<div class="app-shell">' + note, 1)
    note_style = '<style>.preview-note{padding:9px 16px;background:var(--tint);color:var(--text);font-size:12px;text-align:center;line-height:1.5}</style>'
    source = source.replace('</head>', note_style + '</head>', 1)
    return MARKER + '\n' + source


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    destination = parser.add_mutually_exclusive_group()
    destination.add_argument('--output', type=Path)
    destination.add_argument('--share', action='store_true', help='Build a uniquely named HTML and downloadable ZIP in previews/.')
    args = parser.parse_args()
    contents = build_preview()
    payload = contents.encode('utf-8')
    digest = hashlib.sha256(payload).hexdigest()[:12]
    output = (ROOT / 'previews' / f'knowledge-stash-preview-{digest}.html') if args.share else (args.output or ROOT / 'preview.html')
    output = output.resolve()
    if output.exists() and not output.read_text(encoding='utf-8').startswith(MARKER):
        parser.error(f'Refusing to overwrite a file not generated by this tool: {output}')
    archive = output.with_suffix('.zip') if args.share else None
    if archive and archive.exists():
        try:
            with ZipFile(archive) as existing:
                if existing.namelist() != [output.name] or existing.read(output.name) != payload:
                    parser.error(f'Refusing to overwrite an unrelated archive: {archive}')
        except (BadZipFile, OSError):
            parser.error(f'Refusing to overwrite an unreadable archive: {archive}')
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(contents, encoding='utf-8')
    print(f'Built {output} ({len(payload):,} bytes)')
    if archive:
        if not archive.exists():
            with ZipFile(archive, 'x', compression=ZIP_DEFLATED) as bundle:
                bundle.writestr(output.name, payload)
        print(f'Download {archive}')


if __name__ == '__main__':
    main()
